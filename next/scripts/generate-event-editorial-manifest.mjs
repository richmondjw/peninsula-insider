import {captureEventInventory,assertInventoryUnchanged} from './event-editorial-inventory.mjs';
import path from 'node:path';
import {fileURLToPath} from 'node:url';
import {writeFile,readFile,lstat} from 'node:fs/promises';
import {createHash} from 'node:crypto';
import {validateEditorialBuild} from '../../ops/event-intelligence/editorial-build.mjs';
export const disabledManifest={schemaVersion:'pi-editorial-manifest-1.0',enabled:false,entries:[]};
function moduleSource(manifest){return '/** Generated by the trusted editorial build validator. */\nexport const editorialManifest = Object.freeze('+JSON.stringify(manifest)+');\n';}
/** Configuration and its independent pin belong to the build operator, never a content record. */
export async function generateEditorialManifest({target,configPath,configHash,expectedStoreRoot,now=new Date()}={}){
 if(!target)throw Error('Fixed build target required');
 // Clear previous enablement before reading optional configuration or evidence.
 await writeFile(target,moduleSource(disabledManifest));
 if(!configPath)return disabledManifest;
 if(!/^[a-f0-9]{64}$/.test(configHash??'')||!expectedStoreRoot)throw Error('Explicit configuration pin and private root required');
 const info=await lstat(configPath);if(!info.isFile()||info.isSymbolicLink()||info.size>16384)throw Error('Unsafe build configuration');
 const bytes=await readFile(configPath);if(createHash('sha256').update(bytes).digest('hex')!==configHash)throw Error('Build configuration pin changed');
 const config=JSON.parse(bytes);if(config.schemaVersion!==1||config.enabled!==true)throw Error('Explicit enabled configuration required');
 const publicInventory=await captureEventInventory();
 const result=await validateEditorialBuild({enabled:true,storeRoot:config.storeRoot,expectedStoreRoot,planPath:config.planPath,registryPath:config.registryPath,expectedRegistryHash:config.expectedRegistryHash,now,publicInventory});
 if(result.rejected.length)throw Error('Editorial evidence rejected; manifest remains disabled');
 await assertInventoryUnchanged(publicInventory);
 const manifest={schemaVersion:result.schemaVersion,enabled:true,generatedAt:result.generatedAt,entries:result.entries};
 await writeFile(target,moduleSource(manifest));return manifest;
}
const script=fileURLToPath(import.meta.url);
if(process.argv[1]&&path.resolve(process.argv[1])===script){
 const target=fileURLToPath(new URL('../src/lib/event-editorial-manifest.mjs',import.meta.url));
 generateEditorialManifest({target,configPath:process.env.PI_EDITORIAL_BUILD_CONFIG,configHash:process.env.PI_EDITORIAL_BUILD_CONFIG_SHA256,expectedStoreRoot:process.env.PI_EDITORIAL_BUILD_STORE_ROOT}).catch(error=>{console.error('Editorial build failed closed:',error.message);process.exitCode=1;});
}
