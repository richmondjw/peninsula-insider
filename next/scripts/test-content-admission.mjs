#!/usr/bin/env node
import { rm, writeFile } from 'node:fs/promises';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { spawnSync } from 'node:child_process';

const scriptsDir = dirname(fileURLToPath(import.meta.url));
const fixture = join(scriptsDir, '..', 'src', 'content', 'articles', '__content-admission-test__.md');

await writeFile(fixture, `---\ntitle: "Invalid generated shell"\n---\n\n[Content to be generated by test agent]\n`);
try {
  const result = spawnSync(process.execPath, [join(scriptsDir, 'validate-content.mjs')], { stdio: 'inherit' });
  if (result.status === 0) {
    throw new Error('Content admission accepted a deliberately invalid placeholder stub.');
  }
  console.log('Content admission correctly rejected the deliberately invalid placeholder stub.');
} finally {
  await rm(fixture, { force: true });
}
