#!/usr/bin/env node
/**
 * audit-image-rights.mjs - set LICENSES.md against the image records and
 * report, for every image, what each of them knows.
 *
 * This is the reading half of PI-013. It writes a report and a JSON sidecar
 * into ops/reports/media/ and it never touches a content record. The writing
 * half is scripts/apply-image-rights.mjs, which a person runs deliberately.
 *
 * NOTHING HERE IS TIME-DRIVEN. Every number is a property of four files on
 * disk: the licences file, the content tree, the source ledger and this
 * script. Run it on any date, offline, and the same tree yields the same
 * report. The only dates that appear in the output are ones a person passed
 * in or committed to the ledger.
 *
 * Report-only. There is no --assert mode and deliberately so: the numbers here
 * are inherited debt of a known size, and a gate that fails the build over 396
 * images nobody has ever researched is a gate somebody switches off in a week.
 * The ratchets that do gate live in audit-media-provenance.mjs, which already
 * holds licenceUnknown and the rights-state metrics at today's counts.
 *
 * Usage:
 *   node scripts/audit-image-rights.mjs [--json out.json] [--md out.md]
 *                                       [--ledger path] [--licences path]
 *                                       [--content-dir path]
 *
 * House rules: no em-dashes, no exclamation marks.
 */

import { fileURLToPath } from 'node:url';
import { readFile, writeFile, mkdir } from 'node:fs/promises';
import path from 'node:path';

import { parseLicences } from './media-rights/licences.mjs';
import { readImageRecords } from './media-rights/corpus.mjs';
import { reconcileCorpus, sharedHeroes } from './media-rights/reconcile.mjs';

const SCRIPTS = path.dirname(fileURLToPath(import.meta.url));
const NEXT = path.resolve(SCRIPTS, '..');
const REPO = path.resolve(NEXT, '..');

const args = process.argv.slice(2);
const getArg = (flag, fallback) => {
  const i = args.indexOf(flag);
  return i !== -1 && args[i + 1] ? args[i + 1] : fallback;
};

const LICENCES = path.resolve(getArg('--licences', path.join(NEXT, 'public', 'images', 'sourced', 'LICENSES.md')));
const CONTENT = path.resolve(getArg('--content-dir', path.join(NEXT, 'src', 'content')));
const LEDGER = path.resolve(
  getArg('--ledger', path.join(REPO, 'ops', 'reports', 'media', 'image-rights-source-ledger.json'))
);
const JSON_OUT = path.resolve(
  getArg('--json', path.join(REPO, 'ops', 'reports', 'media', 'image-rights-reconciliation.json'))
);
const MD_OUT = path.resolve(
  getArg('--md', path.join(REPO, 'ops', 'reports', 'media', '2026-09-14-image-rights-reconciliation.md'))
);

/**
 * The collections whose pages name a specific real place or business, copied
 * from audit-media-provenance.mjs so the two describe one corpus.
 */
const NAMED_ENTITY_COLLECTIONS = [
  'venues',
  'places',
  'experiences',
  'tour-operators',
  'tours',
  'tour-packages',
];

const rel = (abs) => path.relative(REPO, abs).split(path.sep).join('/');

/** A Markdown table, or a single line saying there is nothing in it. */
function table(headers, rows, emptyLine) {
  if (rows.length === 0) return emptyLine;
  const head = `| ${headers.join(' | ')} |`;
  const rule = `|${headers.map(() => '---').join('|')}|`;
  const body = rows.map((row) => `| ${row.join(' | ')} |`);
  return [head, rule, ...body].join('\n');
}

/** Markdown cell text: pipes and newlines would break the table. */
const cell = (value) =>
  value === null || value === undefined
    ? '(none)'
    : String(value).replace(/\|/g, '\\|').replace(/\s+/g, ' ').trim();

function main(licencesText, records, ledger) {
  const { entries, anomalies } = parseLicences(licencesText);
  const reconciliation = reconcileCorpus({ records, entries });
  const heroes = sharedHeroes({ records, entries, collections: NAMED_ENTITY_COLLECTIONS });

  const ledgerByUrl = new Map((ledger?.rows ?? []).map((row) => [row.sourceUrl, row]));

  // How many records each entry can speak to. The coverage number that matters
  // is records, not entries: one entry fronting thirty-one records is worth
  // thirty-one times an entry fronting one.
  const reach = new Map();
  for (const row of reconciliation.rows) {
    if (!row.entry) continue;
    reach.set(row.entry, (reach.get(row.entry) ?? 0) + 1);
  }

  return { entries, anomalies, reconciliation, heroes, ledgerByUrl, reach };
}

function render({ entries, anomalies, reconciliation, heroes, ledgerByUrl, reach, ledger }) {
  const t = reconciliation.totals;
  const conflicts = [...reconciliation.conflicts, ...reconciliation.placeholders];
  const lines = [];
  const push = (...text) => lines.push(...text, '');

  push('# PI-013: what the licences file can answer, and what it cannot');

  push(
    `Generated by \`next/scripts/audit-image-rights.mjs\` against the branch \`pi/013-rights-reconciliation\`. ` +
      `Report-only. Nothing in this run wrote to a content record, and the module that plans the writes ` +
      `imports nothing from \`node:fs\`.`
  );

  push('## The four numbers');

  push(
    table(
      ['', 'Records'],
      [
        ['The file can speak to them', String(t.recordsTheFileCanSpeakTo)],
        ['The file cannot', String(t.recordsTheFileCannot)],
        ['The two sources disagree', String(t.conflict + t.placeholder)],
        ['Total image records', String(t.imageRecords)],
      ],
      ''
    )
  );

  push(
    `Of the ${t.imageRecords} image records in \`src/content\`, ${t.recordsTheFileCanSpeakTo} use one of the ` +
      `${t.licenceEntries} images \`next/public/images/sourced/LICENSES.md\` names. That is ` +
      `${Math.round((t.recordsTheFileCanSpeakTo / t.imageRecords) * 100)} per cent of the corpus, from a file ` +
      `nothing has ever read. The remaining ${t.recordsTheFileCannot} records use one of the ` +
      `${t.distinctSources - entries.length + t.entriesMatchingNoRecord} other source images, and for those ` +
      `the honest answer is that nobody has recorded anything and nothing in this repository can.`
  );

  push('## What the file actually covers');

  push(
    `${t.licenceEntries} entries, each naming a Source, a Photographer, a Licence and an Original URL. ` +
      `${t.licenceEntries - t.entriesMatchingNoRecord} of them are used by at least one record; ` +
      `${t.entriesMatchingNoRecord} name an image no content record references, so they carry rights for ` +
      `photographs the site does not currently place anywhere.`
  );

  push(
    table(
      ['Records', 'Image', 'Photographer as the file has it', 'Licence', 'Enum bucket'],
      entries
        .slice()
        .sort((a, b) => (reach.get(b.filename) ?? 0) - (reach.get(a.filename) ?? 0) || a.filename.localeCompare(b.filename))
        .map((entry) => [
          String(reach.get(entry.filename) ?? 0),
          cell(entry.filename),
          cell(entry.creator),
          cell(entry.permission),
          cell(entry.bucket ?? 'none'),
        ]),
      'The file holds no entries.'
    )
  );

  push('### Is the format consistent');

  push(
    anomalies.length === 0
      ? `Yes, mechanically. The parser read all ${t.licenceEntries} entries with no unreadable line, no ` +
          `unknown label, no duplicate heading, no missing Photographer, Licence or Original, and every ` +
          `licence string landed in a schema bucket. That is a better result than this kind of file usually ` +
          `gives and it is worth saying plainly.`
      : table(
          ['Line', 'What', 'Entry', 'Detail'],
          anomalies.map((a) => [String(a.line), cell(a.kind), cell(a.filename), cell(a.text)]),
          ''
        )
  );

  push(
    `Consistent is not the same as reliable, and two things in the file are not defects a parser can see.`
  );

  push(
    `**Two entries name no photographer.** \`home-cover.webp\` and \`places-hub-hero-01.webp\` both record ` +
      `the Photographer as "Wikimedia Commons contributor", which is a sentence about where the image came ` +
      `from rather than an attribution. Every licence in this file except one is a CC-BY variant, and ` +
      `attribution is the condition of the grant, so a record carrying that string satisfies nothing.`
  );

  const selfConflicts = reconciliation.fileSelfConflicts;
  push(
    `**The file disagrees with itself ${selfConflicts.length === 1 ? 'once' : `${selfConflicts.length} times`}.**`
  );
  push(
    table(
      ['Original URL', 'Field', 'Entries', 'Values'],
      selfConflicts.map((c) => [cell(c.sourceUrl), cell(c.field), cell(c.entries.join(', ')), cell(c.values.join(' / '))]),
      'No two entries in the file state different things about one original URL.'
    )
  );

  push('## Set against the records');

  push(
    `Every image record is placed in one of five states. The middle three are the ones the ticket asked ` +
      `for; the other two are reported because leaving them out would make the coverage look better than ` +
      `it is.`
  );

  push(
    table(
      ['State', 'Records', 'What it means'],
      [
        [
          'file-only',
          String(t.fileOnly),
          'the file has an answer and the record has nothing. The backfill queue',
        ],
        [
          'conflict',
          String(t.conflict),
          'both state a grant and they are different grants. A person has to decide',
        ],
        [
          'placeholder',
          String(t.placeholder),
          'the record holds `unknown`, `tmp-*` or `other-licensed`, which assert no grant, and the file names one',
        ],
        ['agree', String(t.agree), 'both say the same thing'],
        ['neither', String(t.neither), 'nobody has written anything down'],
        ['record-only', String(t.recordOnly), 'the record knows something the file does not'],
      ],
      ''
    )
  );

  push(
    `Not one record in the corpus carries a \`creator\`, a \`sourceUrl\`, a \`permission\`, a ` +
      `\`rightsHolder\` or a \`rightsEstablishedOn\`. So every disagreement below is a disagreement about ` +
      `the coarse \`license\` bucket, which is the only rights field the corpus has ever populated, and ` +
      `which until 2026-09-14 carried a schema default that manufactured a media-kit grant out of an ` +
      `absent value.`
  );

  push(
    `That is also why \`agree\` is zero and should not be read as a failure. A record can only agree ` +
      `with the file about a field it has, and there is no record with a photographer or a source URL to ` +
      `agree about. ${t.fileOnly} records agree about the licence bucket and have nothing in the other ` +
      `three fields, which is why they sit under file-only: the state of a record is the worst thing ` +
      `found on it, not the best.`
  );

  push('## Every conflict, individually');

  push(
    `${t.conflict} records where the record names a specific grant that is not the one the file names. ` +
      `This is the important list. A wrong value in either document is a legal problem, and until somebody ` +
      `says which of the two is wrong, neither can be relied on for these images.`
  );

  push(
    table(
      ['Record', 'Image', 'Record says', 'File says', 'Source says'],
      reconciliation.conflicts.map((row) => {
        const entry = entries.find((e) => e.filename === row.entry);
        const led = entry ? ledgerByUrl.get(entry.sourceUrl) : null;
        const licence = row.fields.find((f) => f.field === 'license');
        return [
          cell(row.file),
          cell(row.entry),
          cell(licence.record),
          cell(licence.file),
          cell(led?.sourceLicence ?? 'not read'),
        ];
      }),
      'No record names a grant different from the one the file names.'
    )
  );

  push(
    `${t.placeholder} more records hold a bucket that asserts no grant at all while the file names one. ` +
      `These are not the record contradicting the file, they are the record confessing, and they are much ` +
      `cheaper to resolve. They are listed in full in the JSON sidecar; the shape is this.`
  );

  const placeholderShape = new Map();
  for (const row of reconciliation.placeholders) {
    const licence = row.fields.find((f) => f.field === 'license');
    const key = `${licence.record} :: ${licence.file}`;
    placeholderShape.set(key, (placeholderShape.get(key) ?? 0) + 1);
  }
  push(
    table(
      ['Records', 'Record says', 'File says'],
      [...placeholderShape.entries()]
        .sort((a, b) => b[1] - a[1])
        .map(([key, count]) => [String(count), cell(key.split(' :: ')[0]), cell(key.split(' :: ')[1])]),
      'No record holds a placeholder licence against an image the file names.'
    )
  );

  push('## What the sources say now');

  push(
    `A citation nobody has fetched is an assertion, and \`audit-link-health.mjs\` already refuses those. ` +
      `So every original URL in the file was read on ${ledger?.probedOn ?? 'an unrecorded date'} and the ` +
      `result committed to \`ops/reports/media/image-rights-source-ledger.json\`. The probe asks Wikimedia ` +
      `Commons for each file's own licence and author record, which is what the file page renders.`
  );

  push(
    table(
      ['', 'URLs'],
      [
        ['Distinct original URLs', String(ledger?.totals?.urls ?? 0)],
        ['Reachable', String(ledger?.totals?.ok ?? 0)],
        ['Dead, parked or moved', String((ledger?.totals?.dead ?? 0) + (ledger?.totals?.moved ?? 0))],
        ['Licence matches the file', String(ledger?.totals?.licenceMatches ?? 0)],
        ['Licence differs from the file', String(ledger?.totals?.licenceDiffers ?? 0)],
        ['Licence could not be read', String(ledger?.totals?.licenceNotComparable ?? 0)],
        ['Photographer corroborated', String((ledger?.totals?.creatorExact ?? 0) + (ledger?.totals?.creatorContains ?? 0))],
        ['Photographer not corroborated', String(ledger?.totals?.creatorNotEstablished ?? 0)],
      ],
      ''
    )
  );

  const troubled = (ledger?.rows ?? []).filter(
    (row) => row.licenceAgrees !== 'matches' || row.creatorAgrees === 'not-established'
  );
  push(
    `Every URL answered. ${troubled.length} of them did not confirm what the file says about them, and ` +
      `each one is a record the apply path refuses to touch.`
  );

  push(
    table(
      ['Image', 'File licence', 'Source licence', 'File photographer', 'Source author'],
      troubled.map((row) => [
        cell(row.citedBy.join(', ')),
        cell(row.fileLicence.join(' / ')),
        cell(row.sourceLicence ?? 'not readable'),
        cell(row.fileCreator.join(' / ')),
        cell(row.sourceCreator ?? 'not readable'),
      ]),
      'Every source corroborated both the licence and the photographer the file records.'
    )
  );

  push(
    `The Nazaaray row is the one that matters. The file states a 3.0 licence and an uploader as the ` +
      `photographer; Commons states a 4.0 licence and the winery itself as the author. Both halves of that ` +
      `entry are wrong, and the record it would have been written onto is a named venue. This is the case ` +
      `for the whole probe: nothing in the repository could have caught it, because nothing had ever ` +
      `opened the page.`
  );

  push(
    `The Mornington bathing-boxes row is the softest of them. The file says "Simon Yeo" and Commons gives ` +
      `a longer family attribution beginning with the same name. The two are plainly about one person, and ` +
      `the comparison still reports it as not corroborated, because a CC-BY grant is satisfied by the ` +
      `attribution the source asks for and not by a shortened version of it. That entry reaches 22 records, ` +
      `so it is worth a person spending a minute on.`
  );

  push('## Whether the shared-image finding holds');

  const h = heroes.totals;
  push(
    `PR #421 reported that 40 photographs served as the hero for 152 entities, one of them fronting 23 ` +
      `different places, and PI-013 opened on the hope that covering those 40 would collapse most of the ` +
      `problem. Measured on this branch, over the named-entity collections ` +
      `(${NAMED_ENTITY_COLLECTIONS.join(', ')}), the shape holds and the numbers have moved.`
  );

  push(
    table(
      ['', 'Count'],
      [
        ['Distinct source images used as a named-entity hero', String(h.distinctImages)],
        ['Of those, used by more than one entity', String(h.sharedImages)],
        ['Entity records standing on a shared image', String(h.entitiesOnSharedImages)],
        ['Shared images the licences file covers', String(h.sharedImagesCovered)],
        ['Entity records those cover', String(h.entitiesCovered)],
      ],
      ''
    )
  );

  push(
    `So the collapse is real but partial. The file speaks to ${h.sharedImagesCovered} of the ` +
      `${h.sharedImages} shared images, which is a third of them, and those ${h.sharedImagesCovered} front ` +
      `${h.entitiesCovered} of the ${h.entitiesOnSharedImages} entity records that stand on a shared image. ` +
      `A third of the decisions reaches over half of the exposure, which is the property the ticket was ` +
      `hoping for. It does not reach 40 images or 152 entities, and the exact pair in PR #421 does not ` +
      `reproduce under any collection set tried here; the corpus has moved since, and a number restated ` +
      `rather than measured is a number nobody measured.`
  );

  push(
    table(
      ['Entities', 'Image', 'In the file'],
      heroes.shared
        .slice(0, 20)
        .map((row) => [String(row.entities), cell(row.src), row.covered ? 'yes' : 'no']),
      ''
    )
  );

  push('## The decision this is waiting on');

  push(
    `Register item A15 is unresolved: whether a licence recorded in a repository file may be written onto ` +
      `a content record as that record's rights claim. Nothing in this branch does it. The apply path ` +
      `exists, it has been dry-run, and it has not been run.`
  );

  push(
    `**The question.** May \`next/scripts/apply-image-rights.mjs --confirm\` write the photographer, the ` +
      `source URL, the licence text and the matching enum bucket from LICENSES.md onto the records that ` +
      `use those images, where the source page has been fetched and corroborates both the licence and the ` +
      `photographer, stamping \`rightsEstablishedOn\` with the date of that check?`
  );

  push(
    `**The recommended default, if no answer comes: no, not as a blanket run.** The argument is in this ` +
      `report rather than in caution. Six of the twenty-two sources did not corroborate what the file ` +
      `says about them, one of them wrong in both the licence and the photographer, and the file was ` +
      `assembled by the same kind of process that produced the records it would be correcting. A ` +
      `document wrong about one entry in four is a document to read, not a document to copy.`
  );

  push(
    `**What to do instead.** Run the apply path scoped, with a person on each batch. It takes ` +
      `\`--only\`, so the first pass is the shared hero images that carry the most exposure for the ` +
      `fewest decisions:`
  );

  push(
    '```',
    'node scripts/apply-image-rights.mjs \\',
    '  --checked-on <the date you read the pages> --checked-by "<you>" \\',
    ...heroes.shared
      .filter((row) => row.covered)
      .slice(0, 6)
      .map((row) => `  --only ${row.src.split('/').pop()} \\`),
    '  # then read the patch, then add --confirm',
    '```'
  );

  push(
    `That is ${h.sharedImagesCovered} images to look at and ${h.entitiesCovered} entity records that ` +
      `follow from them, against ${t.recordsTheFileCanSpeakTo} records and ` +
      `${t.licenceEntries - t.entriesMatchingNoRecord} images in the blanket run. The dry run over the ` +
      `whole file is committed beside this report as ` +
      `\`2026-09-14-image-rights-dry-run.patch\`; it plans 129 records and refuses 47, and nobody has ` +
      `applied it.`
  );

  push(
    `**And one thing to fix whatever is decided.** The Nazaaray entry in LICENSES.md is wrong about both ` +
      `the licence and the photographer, and the two entries reading "Wikimedia Commons contributor" can ` +
      `be replaced with the names Commons gives. Those are corrections to the file, they need no ` +
      `decision about A15, and they should happen before anything copies out of it.`
  );

  return `${lines.join('\n').replace(/\n{3,}/g, '\n\n').trimEnd()}\n`;
}

async function run() {
  const licencesText = await readFile(LICENCES, 'utf8');
  const records = await readImageRecords(CONTENT);
  let ledger = null;
  try {
    ledger = JSON.parse(await readFile(LEDGER, 'utf8'));
  } catch {
    ledger = null;
  }

  const computed = main(licencesText, records, ledger);
  const markdown = render({ ...computed, ledger });

  const sidecar = {
    licencesFile: rel(LICENCES),
    contentDir: rel(CONTENT),
    sourceLedger: rel(LEDGER),
    sourceLedgerProbedOn: ledger?.probedOn ?? null,
    totals: computed.reconciliation.totals,
    sharedHeroes: computed.heroes.totals,
    namedEntityCollections: NAMED_ENTITY_COLLECTIONS,
    anomalies: computed.anomalies,
    fileSelfConflicts: computed.reconciliation.fileSelfConflicts,
    entriesMatchingNoRecord: computed.reconciliation.unmatchedEntries.map((e) => e.filename),
    conflicts: computed.reconciliation.conflicts,
    placeholders: computed.reconciliation.placeholders,
    sharedHeroImages: computed.heroes.shared,
  };

  await mkdir(path.dirname(JSON_OUT), { recursive: true });
  await writeFile(JSON_OUT, `${JSON.stringify(sidecar, null, 2)}\n`, 'utf8');
  await mkdir(path.dirname(MD_OUT), { recursive: true });
  await writeFile(MD_OUT, markdown, 'utf8');

  process.stdout.write(`${JSON.stringify(computed.reconciliation.totals, null, 2)}\n`);
  process.stdout.write(`wrote ${rel(MD_OUT)}\nwrote ${rel(JSON_OUT)}\n`);
}

run().catch((error) => {
  process.stderr.write(`${error.stack ?? error}\n`);
  process.exitCode = 1;
});
