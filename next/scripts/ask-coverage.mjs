#!/usr/bin/env node
/**
 * What Ask PI cannot do yet, and which pages would fix it.
 *
 * PI plans a day from the published pages in one town, and her tiles carry a
 * photograph only when the page has one of its own. So the gaps in her
 * answers are gaps in the guides. This reads the built Ask index and lists
 * them as a commissioning list: towns where a part of the day cannot be
 * filled, and pages with no photograph.
 *
 *   node scripts/ask-coverage.mjs --dist dist                 print the report
 *   node scripts/ask-coverage.mjs --dist dist --out FILE.md   write it
 *
 * Photographs are counted from the build it is run on. A build made without
 * the live image database (PI_SKIP_CMS_LIVE_READS=1) undercounts them; the
 * report says which kind of build it read.
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { join, resolve } from 'node:path';
import { converse } from '../src/lib/ask-pi.mjs';
import { melbourneDay, sayDay } from '../src/lib/ask-guide.mjs';

const args = process.argv.slice(2);
const option = (name) => (args.includes(name) ? args[args.indexOf(name) + 1] : undefined);
const dist = resolve(option('--dist') || 'dist');
const index = JSON.parse(readFileSync(join(dist, 'ask/index.json'), 'utf8'));
const today = melbourneDay();
const PARTS = { 'To start': 'a cafe or bakery', Then: 'something to do', 'The table': 'a restaurant or pub', After: 'a cellar door' };

// Ask her for a whole day in every town and record what she could not fill.
const towns = [];
for (const place of index.places) {
  const turn = converse(index, `plan a day in ${place.name} for the two of us, the whole day`, null, { today });
  const reply = turn?.reply;
  const filled = reply?.plan ? reply.plan.stops.map((stop) => stop.label) : [];
  const missing = Object.keys(PARTS).filter((part) => !filled.includes(part));
  const pages = index.records.filter((record) => record.p === place.slug && ['eat', 'wine', 'do', 'stay'].includes(record.k) && !record.g);
  // Only a town she can plan can be rescued: without a plan she would pick another town.
  const wet = reply?.plan ? converse(index, 'Rainy day rescue', turn.state, { today })?.reply : null;
  towns.push({
    name: place.name,
    pages: pages.length,
    planned: Boolean(reply?.plan),
    missing,
    swaps: reply?.plan ? reply.plan.stops.filter((stop) => stop.swappable).length : 0,
    stops: filled.length,
    indoor: Boolean(wet?.plan?.stops.some((stop) => stop.label === 'Then')),
    noPhoto: pages.filter((record) => !record.im).map((record) => record.t),
  });
}
towns.sort((a, b) => b.pages - a.pages || a.name.localeCompare(b.name));

const kinds = [['eat', 'Eat and drink'], ['wine', 'Wine'], ['stay', 'Stay'], ['do', 'Things to do'], ['event', "What's on"], ['plan', 'Plans'], ['story', 'Journal']];
const photoRows = kinds.map(([kind, label]) => {
  const all = index.records.filter((record) => record.k === kind && !record.g);
  const without = all.filter((record) => !record.im);
  return { label, all: all.length, without: without.length, titles: without.map((record) => record.t).sort() };
});
const types = {};
for (const record of index.records) if (['eat', 'wine', 'do'].includes(record.k) && !record.g) types[record.ty || 'no type'] = (types[record.ty || 'no type'] || 0) + 1;

const full = towns.filter((town) => town.planned && !town.missing.length);
const partial = towns.filter((town) => town.planned && town.missing.length);
const none = towns.filter((town) => !town.planned);
const lines = [];
const say = (text = '') => lines.push(text);

say('# Ask PI coverage');
say();
say(`Read from the Ask index built on ${sayDay(melbourneDay(new Date(index.generatedAt)))} (${index.count} pages, ${index.places.length} towns). Generated by \`next/scripts/ask-coverage.mjs\`; re-run it after a build rather than editing this file.`);
say();
say('PI plans a day from the published pages in one town. Where a town has no page for a part of the day, she says so and leaves it out. This lists those gaps.');
say();
say('## Whole-day plans by town');
say();
say(`- ${full.length} towns fill all four parts of a day.`);
say(`- ${partial.length} towns get a plan with a part missing.`);
say(`- ${none.length} towns are declined as too thin for a plan.`);
say();
say('| Town | Venue pages | Parts filled | Missing | Stops that can be swapped | Rainy-day option |');
say('| --- | ---: | ---: | --- | ---: | --- |');
for (const town of towns) {
  say(`| ${town.name} | ${town.pages} | ${town.planned ? town.stops : 'no plan'} | ${town.missing.map((part) => PARTS[part]).join(', ') || 'none'} | ${town.swaps} | ${town.planned ? (town.indoor ? 'yes' : 'no') : 'n/a'} |`);
}
say();
say('## What to commission first');
say();
const wanted = {};
for (const town of towns) for (const part of town.missing) (wanted[part] ||= []).push(town);
for (const [part, list] of Object.entries(wanted).sort((a, b) => b[1].length - a[1].length)) {
  const top = list.sort((a, b) => b.pages - a.pages).slice(0, 12).map((town) => town.name).join(', ');
  say(`- **${PARTS[part]}**: missing in ${list.length} of ${towns.length} towns. Largest first: ${top}.`);
}
const planned = towns.filter((town) => town.planned);
say(`- **Something to do under a roof**: ${planned.filter((town) => !town.indoor).length} of the ${planned.length} towns she can plan have none, so "Rainy day rescue" drops that part there.`);
say();
say('Types among the eat, wine and things-to-do pages (golf courses, tours and dated markets are not used as stops): ' + Object.entries(types).sort((a, b) => b[1] - a[1]).map(([type, count]) => `${type} ${count}`).join(', ') + '.');
say();
say('## Pages without a photograph of their own');
say();
say('A tile shows a photograph only when the page it links to shows that photograph itself. These pages do not, so their tiles are text.');
if (args.includes('--snapshot')) {
  say();
  say('**Read this count with care.** This report was run on a build made from the checked-in image snapshot, without the live image database. The live site may show photographs on some of these pages. Re-run on a production build for the true list.');
}
say();
say('| Section | Pages | Without a photograph |');
say('| --- | ---: | ---: |');
for (const row of photoRows) say(`| ${row.label} | ${row.all} | ${row.without} |`);
say();
for (const row of photoRows.filter((entry) => entry.without && ['Eat and drink', 'Wine', 'Stay', 'Things to do'].includes(entry.label))) {
  say(`**${row.label}** (${row.without}): ${row.titles.join(', ')}.`);
  say();
}

const report = lines.join('\n') + '\n';
if (option('--out')) writeFileSync(resolve(option('--out')), report);
else process.stdout.write(report);
console.error(`Ask coverage: ${full.length} towns with a full day, ${partial.length} partial, ${none.length} declined; ${photoRows.slice(0, 4).reduce((sum, row) => sum + row.without, 0)} venue pages without a photograph.`);
